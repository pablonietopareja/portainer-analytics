"""Release metadata, deterministic archives and publication-boundary regression checks."""

from __future__ import annotations

import contextlib
import hashlib
import io
import json
import os
import subprocess
import sys
import tarfile
import tempfile
import unittest
import zipfile
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import portainer_console as console
from scripts import build_release


class ReleaseTests(unittest.TestCase):
    def test_runtime_and_node_versions_agree_with_release_version(self):
        root = build_release.ROOT
        version = (root / "VERSION").read_text(encoding="utf-8").strip()
        self.assertEqual(version, "1.0.0")
        self.assertEqual(console.VERSION, version)
        self.assertEqual(console.Handler.server_version, "PortainerAnalytics/" + version)
        package = json.loads((root / "package.json").read_text(encoding="utf-8"))
        lock = json.loads((root / "package-lock.json").read_text(encoding="utf-8"))
        for actual in (package["version"], lock["version"], lock["packages"][""]["version"]):
            self.assertEqual(actual, version)
        output = subprocess.check_output(
            [sys.executable, "portainer_console.py", "--version"],
            cwd=root,
            text=True,
            timeout=15,
        ).strip()
        self.assertEqual(output, "Portainer Analytics " + version)

    def test_stable_version_names_and_invalid_versions(self):
        for version in ("0.0.0", "1.0.0", "12.34.567"):
            with self.subTest(version=version):
                self.assertEqual(
                    build_release.release_name(version), "portainer-analytics-" + version
                )
        for version in (
            "1.0",
            "v1.0.0",
            "01.0.0",
            "1.00.0",
            "1.0.0-rc.1",
            "1.0.0+build",
            "../1.0.0",
        ):
            with self.subTest(version=version), self.assertRaises(ValueError):
                build_release.release_name(version)

    def test_archive_names_contents_checksums_and_reproducibility(self):
        with tempfile.TemporaryDirectory(prefix="portainer-release-test-") as directory:
            root = Path(directory)
            for name in build_release.RUNTIME + build_release.SOURCE:
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text("# synthetic release fixture\n", encoding="utf-8")
            (root / "VERSION").write_text("1.0.0\n", encoding="utf-8")
            fixture_files = {
                "web/console.css": b"body { color: white; }\n",
                "tests/check.py": b"# Synthetic test\n",
                "docs/DEPLOYMENT.md": b"# Deployment\n",
                "imgs/overview.png": b"synthetic-image-fixture",
                ".github/workflows/ci.yml": b"name: CI\n",
            }
            for name, data in fixture_files.items():
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
            # Local state and generated bytecode must never enter either archive.
            for name in (".env", "data/console.sqlite3", "tests/__pycache__/cached.py"):
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text("local state", encoding="utf-8")
            with (
                mock.patch.object(build_release, "ROOT", root),
                contextlib.redirect_stdout(io.StringIO()),
            ):
                expected = set(build_release.RUNTIME + build_release.SOURCE) | set(fixture_files)
                self.assertEqual(set(build_release.source_files()), expected)
                build_release.main()
                output = root / "dist"
                names = {
                    "portainer-analytics-1.0.0-source.zip",
                    "portainer-analytics-1.0.0-build-context.tar",
                    "SHA256SUMS",
                }
                self.assertEqual({path.name for path in output.iterdir()}, names)
                before = {path.name: path.read_bytes() for path in output.iterdir()}
                build_release.main()
                self.assertEqual(
                    before, {path.name: path.read_bytes() for path in output.iterdir()}
                )
                with zipfile.ZipFile(output / "portainer-analytics-1.0.0-source.zip") as archive:
                    self.assertEqual(set(archive.namelist()), expected)
                    self.assertTrue(
                        all(item.date_time == (1980, 1, 1, 0, 0, 0) for item in archive.infolist())
                    )
                    self.assertTrue(all(item.create_system == 3 for item in archive.infolist()))
                with tarfile.open(
                    output / "portainer-analytics-1.0.0-build-context.tar"
                ) as archive:
                    self.assertEqual(
                        set(archive.getnames()), set(build_release.RUNTIME) | {"web/console.css"}
                    )
                    self.assertTrue(
                        all(item.mtime == 0 and item.mode == 0o644 for item in archive.getmembers())
                    )
                self.assertNotIn(b"\r", (output / "SHA256SUMS").read_bytes())
                for line in (output / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
                    digest, name = line.split("  ")
                    self.assertEqual(
                        digest, hashlib.sha256((output / name).read_bytes()).hexdigest()
                    )

    def test_unsafe_archive_paths_and_credential_like_content_are_rejected(self):
        with tempfile.TemporaryDirectory(prefix="portainer-release-boundary-") as directory:
            root = Path(directory)
            (root / "VERSION").write_text("1.0.0\n", encoding="utf-8")
            (root / "nested").mkdir()
            with mock.patch.object(build_release, "ROOT", root):
                for name in (
                    "../outside",
                    "nested/../VERSION",
                    "../VERSION",
                    "nested\\..\\VERSION",
                    "C:/VERSION",
                    "C:VERSION",
                    "C:\\VERSION",
                    "/VERSION",
                    "//server/share/VERSION",
                    "\\\\server\\share\\VERSION",
                    "",
                    "./VERSION",
                    "nested//VERSION",
                    "nested/VERSION/",
                    "missing.txt",
                ):
                    with self.subTest(path=name), self.assertRaises(ValueError):
                        build_release.read_files([name])
                (root / "secret.txt").write_text("ptr_" + "X" * 36, encoding="utf-8")
                with self.assertRaisesRegex(ValueError, "Credential-like content"):
                    build_release.read_files(["secret.txt"])

    def test_noncanonical_root_accepts_nested_files_and_checks_credentials(self):
        with tempfile.TemporaryDirectory(prefix="portainer-release-root-") as directory:
            root = Path(directory)
            (root / "alias-component").mkdir()
            (root / "nested").mkdir()
            (root / ".dockerignore").write_bytes(b"synthetic fixture\n")
            (root / "nested" / "ordinary.txt").write_bytes(b"nested fixture\n")
            (root / "secret.txt").write_text("ptr_" + "X" * 36, encoding="utf-8")
            noncanonical = root / "alias-component" / ".."
            with mock.patch.object(build_release, "ROOT", noncanonical):
                self.assertEqual(
                    build_release.read_files([".dockerignore", "nested/ordinary.txt"]),
                    {
                        ".dockerignore": b"synthetic fixture\n",
                        "nested/ordinary.txt": b"nested fixture\n",
                    },
                )
                with self.assertRaisesRegex(ValueError, "Credential-like content"):
                    build_release.read_files(["secret.txt"])

    def test_linked_root_accepts_files_but_rejects_link_escape(self):
        with tempfile.TemporaryDirectory(prefix="portainer-release-junction-") as directory:
            base = Path(directory)
            root, outside = base / "root", base / "outside"
            root.mkdir()
            outside.mkdir()
            (root / ".dockerignore").write_bytes(b"synthetic fixture\n")
            (root / "nested").mkdir()
            (root / "nested" / "ordinary.txt").write_bytes(b"nested fixture\n")
            (root / "secret.txt").write_text("ptr_" + "X" * 36, encoding="utf-8")
            (outside / "ordinary.txt").write_bytes(b"outside fixture\n")
            alias, escape = base / "root-alias", root / "escape"
            links = []
            try:
                for link, target in ((alias, root), (escape, outside)):
                    if os.name == "nt":
                        # Junctions exercise Windows aliases without symlink privileges.
                        result = subprocess.run(
                            ["cmd", "/c", "mklink", "/J", str(link), str(target)],
                            capture_output=True,
                            timeout=15,
                        )
                        self.assertEqual(
                            result.returncode, 0, "Could not create the NTFS junction test fixture"
                        )
                    else:
                        link.symlink_to(target, target_is_directory=True)
                    links.append(link)
                self.assertNotEqual(alias, alias.resolve())
                with mock.patch.object(build_release, "ROOT", alias):
                    self.assertEqual(
                        build_release.read_files([".dockerignore", "nested/ordinary.txt"]),
                        {
                            ".dockerignore": b"synthetic fixture\n",
                            "nested/ordinary.txt": b"nested fixture\n",
                        },
                    )
                    with self.assertRaisesRegex(ValueError, "Credential-like content"):
                        build_release.read_files(["secret.txt"])
                    with self.assertRaisesRegex(ValueError, "Invalid or missing release file"):
                        build_release.read_files(["escape/ordinary.txt"])
                    if os.name != "nt":
                        file_link = root / "file-link.txt"
                        file_link.symlink_to(root / ".dockerignore")
                        links.append(file_link)
                        with self.assertRaisesRegex(ValueError, "Invalid or missing release file"):
                            build_release.read_files(["file-link.txt"])
            finally:
                # Remove only link entries, never their target directories.
                for link in reversed(links):
                    if os.name == "nt":
                        link.rmdir()
                    else:
                        link.unlink()


if __name__ == "__main__":
    unittest.main()
